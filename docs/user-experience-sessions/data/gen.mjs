// Regenerates every JSON fixture in this folder:
//   node --experimental-transform-types docs/user-experience-sessions/data/gen.mjs
// The data is relative to TODAY (see lib.mjs); change TODAY there and rerun to move the whole history.
import { writeFileSync } from 'node:fs'

import { buildBuilding } from './building.mjs'
import { buildEmployee } from './employee.mjs'
import * as L from './lib.mjs'
import { buildMerchant } from './merchant.mjs'
import { buildMother } from './mother.mjs'

const here = name => new URL(name, import.meta.url)

/** One row per line keeps the files diff-able and readable. */
function dump(file, data) {
  const body = Object.entries(data)
    .map(([tab, rows]) => `  ${JSON.stringify(tab)}: [\n${rows.map(r => `    ${JSON.stringify(r)}`).join(',\n')}\n  ]`)
    .join(',\n')

  writeFileSync(here(file), `{\n${body}\n}\n`)
}

const dumpSms = (file, list) =>
  writeFileSync(here(file), `[\n${list.map(s => `  ${JSON.stringify(s)}`).join(',\n')}\n]\n`)

const mother = buildMother()
const employee = buildEmployee()
const merchant = buildMerchant()
const building = buildBuilding()

dump('mother.json', mother.data)
dump('employee.json', employee.data)
dump('merchant-manager.json', merchant.data)
dump('merchant-building.json', building.data)

dumpSms('sms-mother.json', mother.sms)
dumpSms('sms-employee.json', employee.sms)
dumpSms('sms-merchant.json', merchant.sms)
dumpSms('sms-merchant-building.json', building.sms)

// Role of each SMS in the «مانده» chain (recorded / pending / pending-off / redelivery); check.mjs reads it.
const chain = { mother, employee, 'merchant-manager': merchant, 'merchant-building': building }
const chainBody = Object.entries(chain)
  .map(([name, x]) => `  ${JSON.stringify(name)}: [\n${x.meta.map(m => `    ${JSON.stringify(m)}`).join(',\n')}\n  ]`)
  .join(',\n')

writeFileSync(here('sms-balance-chain.json'), `{\n${chainBody}\n}\n`)

// ---- init scripts for `qa-shoot.mjs --init`: they only edit localStorage, after the runner's seed.
const SPREADSHEET_ID = 'mock-spreadsheet-perf-test' // e2e/helpers/mockAppSeed.json

function listsOf(data) {
  const groups = L.catGroups.rowsToGroups(data[L.names.CATEGORIES_SHEET].slice(1))

  return groups
}

function initScript(data, { building = false } = {}) {
  const g = listsOf(data)

  return `// Generated by gen.mjs. Run with: qa-shoot.mjs --init <this file>
// Puts the category lists of the CATEGORIES tab into the saved settings (the app otherwise only
// syncs them from the sheet when a records/debts page is opened) and fixes the currency unit.
;(() => {
  const lists = ${JSON.stringify({ income: g.income, expense: g.expense })}
  const settings = JSON.parse(localStorage.getItem('accounting_settings') || '{}')

  settings.currency = 'toman'
  settings.forms = (settings.forms || []).map(form => ({
    ...form,
    fields: form.fields.map(field =>
      field.id === 'category' && lists[form.type] ? { ...field, options: lists[form.type] } : field
    )
  }))
  settings.dangCategories = ${JSON.stringify(g.dang)}
  settings.receivableCategories = ${JSON.stringify(g.receivable)}
${
  building
    ? `
  // A building is its own spreadsheet: mark the mock one as a building (the tab «تنظیمات دوره»
  // row «نوع فضا» says the same) and make the 'perf@test.local' session its manager.
  settings.spreadsheets = (settings.spreadsheets || []).map(s => ({ ...s, name: 'مجتمع مسکونی یاس', kind: 'building' }))
  localStorage.setItem('accounting_workspace_v1', JSON.stringify({ '${SPREADSHEET_ID}': 'building' }))
`
    : ''
}  localStorage.setItem('accounting_settings', JSON.stringify(settings))
})()
`
}

writeFileSync(here('init-mother.js'), initScript(mother.data))
writeFileSync(here('init-employee.js'), initScript(employee.data))
writeFileSync(here('init-merchant-manager.js'), initScript(merchant.data))
writeFileSync(here('init-merchant-building.js'), initScript(building.data, { building: true }))

console.log('written')
